//! HID report descriptors.
//!
//! All Gen2 models share the same shape: report id `0x01` carries the input
//! report, `0x02` the 1024-byte output report, and `0x03..` are 32-byte feature
//! reports. Studio additionally declares the feature ids it answers over USB
//! (`0x0b`, `0x0c`, `0x0d`, `0x11`, `0x13`).
//!
//! The exact byte sequence must match the real device for the official app to
//! accept it; the constants below mirror the existing firmware descriptor and
//! are extended for Studio. `docs/usb-hid.md` records the captured descriptor
//! once U0 is available.

use crate::model::{ModelId, ModelInfo};

macro_rules! gen2_descriptor {
    ($($id:expr),* $(,)?) => {
        &[
            // Usage page (consumer), usage 1, application collection
            0x05, 0x0c, 0x09, 0x01, 0xa1, 0x01,
            // Report id 1: input, 48 bytes (button/encoder/NFC reports)
            0x09, 0x01, 0x05, 0x09, 0x19, 0x01, 0x29, 0x30,
            0x15, 0x00, 0x26, 0xff, 0x00, 0x75, 0x08, 0x95, 0x30,
            0x85, 0x01, 0x81, 0x02,
            // Report id 2: output, 1024 bytes
            0x0a, 0x00, 0xff, 0x15, 0x00, 0x26, 0xff, 0x00,
            0x75, 0x08, 0x96, 0x00, 0x04, 0x85, 0x02, 0x91, 0x02,
            // Feature reports, 32 bytes each
            $(
                0x0a, 0x00, 0xff, 0x15, 0x00, 0x26, 0xff, 0x00,
                0x75, 0x08, 0x95, 0x20, 0x85, $id, 0xb1, 0x04,
            )*
            0xc0,
        ]
    };
}

/// Descriptor for every non-Studio Gen2 model.
pub static GEN2_HID_DESCRIPTOR: &[u8] = gen2_descriptor!(0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x0a);

