/// Descriptor for a model.
pub fn descriptor_for(model: &ModelInfo) -> &'static [u8] {
    match model.id {
        ModelId::Studio => STUDIO_HID_DESCRIPTOR,
        _ => GEN2_HID_DESCRIPTOR,
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model;

    fn assert_balanced(desc: &[u8]) {
        let mut collections = 0i32;
        let mut i = 0;
        while i < desc.len() {
            let b = desc[i];
            let (size, tag, kind) = (b & 0x03, (b >> 4) & 0x0f, (b >> 2) & 0x03);
            let len = match size {
                0 => 0,
                1 => 1,
                2 => 2,
                _ => 4,
            } as usize;
            if kind == 0 {
                // Main item
                match tag {
                    0xa => collections += 1, // Collection
                    0xc => collections -= 1, // End collection
                    _ => {}
                }
            }
            i += 1 + len;
        }
        assert_eq!(collections, 0, "unbalanced HID descriptor");
    }

    #[test]
    fn gen2_descriptor_is_balanced() {
        assert_balanced(GEN2_HID_DESCRIPTOR);
    }

    #[test]
    fn studio_descriptor_is_balanced_and_has_enterprise_features() {
        assert_balanced(STUDIO_HID_DESCRIPTOR);
        for id in [0x0bu8, 0x0c, 0x0d, 0x11, 0x13] {
            assert!(
                STUDIO_HID_DESCRIPTOR.windows(2).any(|w| w == [0x85, id]),
                "missing feature report {id:#04x}"
            );
        }
    }

    #[test]
    fn studio_selects_studio_descriptor() {
        assert_eq!(descriptor_for(&model::STUDIO), STUDIO_HID_DESCRIPTOR);
        assert_eq!(descriptor_for(&model::XL), GEN2_HID_DESCRIPTOR);
    }
}
